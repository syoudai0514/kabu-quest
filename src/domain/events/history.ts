/**
 * 歴史イベントカタログ（じだいのタネあかし）
 *
 * 各イベントは「なにが おきたか → ひとびとは どうしたか → そのあと どうなったか」
 * の3幕構成を厳守し、教訓は明文化せず最後にフクじいの問いかけで終える（GDD §6.6）。
 * cores = そのイベントを「体験した」とみなす月。旅の窓にcoreが含まれたら帰還時に語られる。
 * hints = プレイ中に時代を匂わせるニュースカード（年号は絶対に出さない）。
 */
import type { MonthId } from '../types';
import { monthAdd } from '../market/series';

export interface HistoricalEvent {
  id: string;
  /** 大きいほどタネあかしの主役になる */
  priority: number;
  /** この月が旅の窓に含まれたら「体験した」 */
  cores: MonthId[];
  /** 図鑑・親レポートに表示する期間 */
  period: { from: MonthId; to: MonthId };
  kidTitle: string;
  adultTitle: string;
  /** 紙芝居。1要素=1枚。ひらがな中心 */
  story: string[];
  /** フクじいの締めの問いかけ（親子の会話への送りパス） */
  question: string;
  hints: Array<{ month: MonthId; text: string }>;
  /** 災害等、保護者が表示可否を選べるイベント（せってい参照） */
  sensitive?: boolean;
}

