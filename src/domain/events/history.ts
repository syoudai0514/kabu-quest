/** 旅の窓 [startMonth, endMonth] で体験したイベントを重要度順に返す */
export function matchEvents(
  windowStart: MonthId,
  lengthMonths: number,
  opts: { includeSensitive?: boolean } = {},
): HistoricalEvent[] {
  const windowEnd = monthAdd(windowStart, lengthMonths);
  return HISTORICAL_EVENTS.filter(
    (e) =>
      (opts.includeSensitive !== false || !e.sensitive) &&
      e.cores.some((c) => c >= windowStart && c <= windowEnd),
  ).sort((a, b) => b.priority - a.priority);
}

/** 特定月のニュースカード（イベント固有のヒント）。なければnull */
export function hintForMonth(month: MonthId, opts: { includeSensitive?: boolean } = {}): string | null {
  for (const e of HISTORICAL_EVENTS) {
    if (opts.includeSensitive === false && e.sensitive) continue;
    const hit = e.hints.find((h) => h.month === month);
    if (hit) return hit.text;
  }
  return null;
}

